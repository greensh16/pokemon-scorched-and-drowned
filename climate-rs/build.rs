//! Generates `species.rs` from the game's `include/constants/species.h`, so the Rust
//! encounter rules use the same species numbers as the C game and can't drift.
//!
//! Output: `$OUT_DIR/species.rs`, one `pub const NAME: u16 = N;` per species
//! (the `SPECIES_` prefix dropped), included by `src/species.rs`.

use std::{collections::BTreeMap, env, fs, path::PathBuf};

fn main() {
    let header = PathBuf::from("../include/constants/species.h");
    println!("cargo:rerun-if-changed={}", header.display());
    println!("cargo:rerun-if-changed=build.rs");

    let text = fs::read_to_string(&header).unwrap_or_else(|e| {
        panic!(
            "climate-rs must live inside the game repo: can't read {} ({e})",
            header.display()
        )
    });

    // Pass 1: `SPECIES_X = 123,` and aliases `SPECIES_X = SPECIES_Y,`.
    let mut numbers: BTreeMap<String, u16> = BTreeMap::new();
    let mut aliases: Vec<(String, String)> = Vec::new();
    for line in text.lines() {
        let line = line.trim();
        let Some(rest) = line.strip_prefix("SPECIES_") else { continue };
        let Some((name, value)) = rest.split_once('=') else { continue };
        let name = name.trim();
        let value = value.trim().trim_end_matches(',').trim();
        if !is_ident(name) {
            continue;
        }
        if let Ok(n) = value.parse::<u16>() {
            numbers.insert(name.to_string(), n);
        } else if let Some(target) = value.strip_prefix("SPECIES_") {
            if is_ident(target) {
                aliases.push((name.to_string(), target.to_string()));
            }
        }
    }

    // Pass 2: resolve aliases (they point at numeric entries).
    for (name, target) in aliases {
        if let Some(&n) = numbers.get(&target) {
            numbers.entry(name).or_insert(n);
        }
    }

    assert!(
        numbers.get("POOCHYENA") == Some(&261),
        "species.h parse looks wrong (POOCHYENA should be 261)"
    );

    let mut out = String::from("// Generated by build.rs from include/constants/species.h. Do not edit.\n");
    for (name, n) in &numbers {
        out += &format!("pub const {name}: u16 = {n};\n");
    }
    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("species.rs");
    fs::write(dest, out).unwrap();
}

fn is_ident(s: &str) -> bool {
    let mut chars = s.chars();
    matches!(chars.next(), Some(c) if c.is_ascii_uppercase())
        && chars.all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_')
}
